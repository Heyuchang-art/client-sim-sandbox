# ============ 一、项目背景与意义 ============
h1("一、项目背景与意义")

para("证券客户营销的日常工作，起点都是一次取数。「把总资产 500 万以上、近三个月有交易、还没配置过权益类产品的客户圈出来」，这是客户经理每周都要提出的需求。但在多数券商里，这句话要走到结果，路径是：业务人员写需求单 → 提给数据团队 → 排队排期 → 数据团队回头确认口径 → 出数。整个过程以天为单位。需求越贴近一线、越口语化，往返确认的轮次越多。赛题要求把这个环节的响应时间从「天」压到「分钟」，让业务人员用自然语言直接取到数。")

para("这件事的难点不在于把一句话翻译成 SQL。真正的难点有三个。第一是口径散落：同一句「活跃客户」，在客户信息表、交易表、资金流水表里可能对应三种定义，模型如果不知道业务口径，写出的 SQL 语法完全正确、结果却与报表对不上。第二是模型幻觉：语言模型会臆造出不存在的表名和字段名，也会把 A 表的字段写到 B 表上，这类错误不会报错，只会安静地给出一个错数。第三是不可复核：只给一个数字，业务人员无法判断它算得对不对，也无法向合规解释这个数是怎么来的。")

para("我们的解法围绕这三件事展开。用元数据作为约束：把九张业务表的表定义、25 个指标口径、11 条业务术语和可调用的工具整理成机器可读的登记表，模型只能在这个范围内写查询，写不出登记表以外的字段。用三层安全围栏作为兜底：结构层拦住写操作与无上限查询，语义层按表校验字段并核验指标是否登记，结果层检查行数、列数与数值合理性。用评测流程作为闭环：50 条标准问句、15 条留出问句与 12 条能力边界问句构成可复现的回归集，逐条与人工编写的对照查询比对，低分项交由模型打分与人工复核。")

para("我们在这个基础上多做了一步。取数只回答「有多少、有多少钱」，而业务人员真正要决策的往往是「如果这么做会怎样」。因此我们把问数结果与客户行为沙盘打通：取到的客户名单可以直接带进群体行为推演，看这批客户在暴跌行情下对某套沟通策略的反应，包括恐慌峰值、卖出倾向、投诉与流失风险。这条「取数 → 推演」的闭环，是这套系统区别于普通 NL2SQL 工具的地方。")

