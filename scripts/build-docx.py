h2("3.2 安全围栏：表、指标、结果的合法性验证（攻关任务二）")
para("赛题要求设计安全围栏模块，包括但不限于表、指标、结果的合法性验证，一方面尽可能减少大模型幻觉，另一方面降低幻觉带来的影响。我们的围栏分三层，每一层的拦截范围都是确定性的规则，不依赖模型自述：结构层判断这条语句能不能执行，语义层判断它引用的表、字段、指标是否存在，结果层判断算出来的数是否合理。")
para("严格程度的分工是有意设计的：出现即拦截的必须是确定性错误（写操作、多语句、未知表、跨表字段、未登记指标），而「可疑但可能正确」的情况只提醒不拦截（行数偏多、金额量级异常、空结果）。如果把后者也做成拦截，正常的长尾查询会被误杀成拒绝服务，业务人员会觉得系统不可用。")
