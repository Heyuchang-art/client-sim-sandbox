# ============ 一、项目背景与意义 ============
h1("一、项目背景与意义")

para("证券公司在极端行情下的客户服务面对三个同时出现的约束。第一是时间：行情下跌当天客户情绪上升最快，服务动作必须在数小时内铺开，事后复盘无法挽回已经发生的投诉与流失。第二是一致性：同一套服务策略由不同客户经理执行，话术分寸、触达节奏和风险揭示的完整程度差异很大，越权推荐和承诺收益类表达往往出现在这类高压的临场沟通中。第三是合规：适当性管理要求把合适的产品提供给合适的客户，而当市场波动放大时，最容易出问题的恰恰是向风险承受能力偏低的客户推送高波动产品的动作。")

para("现有的两类工具都无法同时回应这三重约束。以 ChatGPT 类通用大模型为主体的客服或分析工具，可以生成通顺的策略文本，但既给不出可复现的群体量化结果，也无法保证输出不越过合规红线，同一段提示词在不同时间会得到不同结论。传统的客户画像与标签系统擅长描述客户当前状态，却不能回答一个前瞻性问题：如果我们今天用这套话术去触达这批客户，24 小时后他们的卖出倾向、投诉风险和流失概率会变成什么样。")

para("我们把这一缺口作为项目切入点。所谓客户行为沙盘，是指在策略真正触达客户之前，先用一群虚拟客户把这条策略跑一遍。虚拟客户不是随机数，而是由真实客户画像聚类生成的原型智能体，各自带有风险偏好、亏损容忍度、从众敏感度、投资纪律、长期耐心和机构信任六项心理参数，并处在相似性、社交影响、统一服务触达三类关系网络之中。策略进入模拟之后，客户会因为恐慌而产生卖出倾向，也会因为邻居的情绪传导而放大恐慌，还会因为机构主动、差异化、合规的沟通而恢复信任。模拟结束后，输出的是分群接受情况、恐慌峰值、投诉风险、流失概率和应当优先人工介入的客户队列。")

para("这件事的意义在于把客户服务策略的评估节点从触达之后前移到触达之前。券商不需要先向真实客户发出可能有问题的内容，再根据结果补救；而是在沙盘里先看一遍结果，再决定是否发出、发给谁、用什么话术。这与主办方提出的通用智能体方向高度契合：智能体承担的是理解业务目标、自主规划步骤、调用工具、检查合规边界、输出解释的职责，而不是简单地生成一段文字。")

