# ============ 五、创新点 ============
h1("五、创新点")

para("本项目的创新点分为一条主创新与四项支撑创新。主创新回答「这个产品能做什么是别的工具做不到的」，支撑创新回答「为什么它能做到、且结果可以被信任」。")

h2("5.1 主创新：在触达客户之前，预演客户群体的反应")

para("多智能体行为模拟在金融领域的常见用法是预测市场：让不同风格的交易者博弈，推演价格冲击。我们把同样的思路转向客户经营，让虚拟客户对服务策略作出反应。这一转向带来的差异是评价对象的变化：市场模拟关心价格，客户模拟关心的是接受、信任、投诉与流失。项目显式建模了客户的从众效应、情绪扩散与分群差异，三类关系边分别代表相似性、社交影响与统一服务触达，在 300 名客户下生成约 900 条可复现的关系边参与传播计算，并纳入消融实验验证其贡献。")

para("这条主线由四个相互咬合的机制组成，缺一不可。")

bullet("客户级状态建模：每位客户有自己的六项心理参数、持仓弹性与历史状态，不是把客群当成一个平均值。同一场下跌下，不同客户的恐慌、卖出与流失各不相同。")

bullet("三类关系网络上的情绪传导：相似性、社交影响与统一服务触达三类关系边参与邻居状态更新，因此情绪会扩散、会放大，也会因为关键节点被干预而收敛——这是只看单个客户的画像工具给不出的。")

bullet("策略作为可干预变量：三套候选沟通方案各自改变触达覆盖率、人工深度与话术贴合度，模拟回答的是「换一种沟通方式，客户反应会怎么变」，而不是只描述客户现状。")

para("在模拟中，干预生效之后客户的期末恐慌会回落到接近零，如果按期末状态给客户排序，就会得到一份人人低风险的名单，失去业务价值。我们改为记录每位客户在整个模拟窗口内的峰值风险暴露，并以此为口径生成干预队列与优先级，同时保留逐时间步状态用于回放。这项调整让系统的输出从描述性指标变成可执行的行动清单。")

para("四者合起来的结果是：把客户服务策略的评估节点从「触达之后」前移到「触达之前」，并且在同一个沙盘里同时回答「该不该发、发给谁、怎么说、大概会怎样」。")

h2("5.2 支撑创新一：沟通策略的参数化建模与引擎侧搜索")

para("策略比较类功能最容易出现的缺陷是结论被写死：三套方案只差几个常数，而排序公式恰好只包含其中一套占优的维度，于是无论什么场景都是同一套方案获胜。本项目在早期版本存在这一缺陷（840 个场景中由分群沟通 100% 夺冠），重构后改为参数化建模：策略由触达覆盖率、人工深度、内容个性化三个杠杆定义，其余参数由杠杆推导；安抚经逐客户门控生效，覆盖率因此成为真实输入；推荐顺序由净效用在每个场景算出，净效用等于避险收益减去触达成本与唤醒成本。三套锚点退化为参数空间中的三个点，引擎另外在该空间做 27 点网格搜索。需要如实说明的是：效用权重是业务参数而非模型参数——避险收益与触达成本量纲不同，二者的兑换率无法从合成数据估计，只能由业务方设定；因此我们的结论只建立在与权重无关的结构性质上（跌幅越大、推荐方案的人工深度不下降，90 条场景序列零违反），而把夺冠配比连同权重敏感性曲面一并披露。另有两点边界：搜索结果只按参数直接评估，尚未生成草稿文本、也未经合规审查，因此不作为可执行推荐；异步任务链路与同步调试接口均已开启该搜索。")

h2("5.3 支撑创新二：模型与数值引擎职责分离")

para("通用智能体项目常见的做法是把全部判断交给模型，代价是不可复现与不可审计。我们把模型限制在它擅长的环节：理解目标、规划步骤、抽取参数、起草策略、解释结果；把大规模群体模拟与合规判定交给确定性代码。由此得到两个直接好处：同一场景与种子必然复现，聚合签名可以像单元测试一样做回归；模型措辞的变化不会改变数值结论，审计时可以把模型版本与规则版本分开追溯。")

h2("5.4 支撑创新三：合规作为不可绕过的硬边界")

para("合规检查在本项目中不是模型的一环，而是位于模型之外的执行器。规则以注册表形式管理，附带否定语境识别与适当性矩阵。关键设计是：策略草稿在进入数值模拟之前先过合规审查，命中阻断级规则时既强制改写为合规版本，又清除该违规话术在模拟中的情绪放大通道。因此合规拦截会真实改变模拟结果，而不是只改写一段展示文本——关闭合规层会让统一风险提示策略的恐慌峰值上升 5.4 个百分点，这一差异在消融实验中可复现。规则集同时服务于模拟流程与独立的检查接口，避免出现两套口径。我们把这一点视为智能体进入金融业务的前置条件。")

h2("5.5 支撑创新四：可验证的评测体系")

para("项目建立了四类可复现的评测材料：20 个标准业务任务用于衡量链路完整率与场景抽取一致率，630 个参数的扫描场景用于检验沟通策略推荐的结构性质与权重敏感性，32 条带标签的合规语料用于衡量召回率与误拦截率，四个消融开关与四种对照模式用于说明各层贡献与方案必要性。所有指标由脚本自动生成并记录版本号、规则版本、随机种子与样本量。我们已经移除了「规划成功率」这类在未接入模型时完全无法失败的指标，并新增了跨效用权重的单调性检验；但仍需如实说明：剩余指标里有少数与标定目标存在耦合（例如断言三种方案都能夺冠，其配比随权重变化），这类指标只能作为回归守卫，不构成独立验证，已在口径说明中标注。")


