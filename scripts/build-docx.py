figure("artifacts/diagrams/02-Agent-Loop时序.png", "图 2 Agent Loop 执行时序与 SSE 事件序列", 15.6)
para("需要说明的是，上面这条八步链路是任务成功时的完整路径，不是写死的工作流。Planner 拿到的是目标与可用工具清单，由它决定用哪些工具、按什么顺序调用；下面的三种情形说明执行过程确实存在判断与调整。")

bullet("工具可跳过：目标中不含客群限定时，Planner 不会生成客户筛选步骤；只需要看当前群体状态时，模拟与合规仍会执行，但报告步骤可以省略汇总以外的章节。工具序列因此不是恒定八步。")

bullet("结果可触发重规划：客户筛选命中数量不足目标客群规模时，执行器不会直接报错，而是按回撤从高到低补足，并在界面与审计中标注命中不足与补足数量；该情形下筛选步骤的审计状态标为待确认，而不是已完成。")

bullet("失败可回退重试：合规审查命中阻断级规则时，策略草稿被改写为合规版本并重新进入检查；单个步骤调用超时会按指数退避重试，上限两次。若模型输出格式不合格，规划结果退回内置模板并记录降级原因，任务继续而不是中断。")

para("上述分支在审计轨迹中留有痕迹：每一步记录状态（已完成、待确认、已拦截）与真实时间戳，重试会单独产生 step.failed 事件。评委可以据此区分「按计划执行」与「执行过程中改变了计划」。")


