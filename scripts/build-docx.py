h1("三、技术方案")
h2("3.1 元数据设计：表、指标、术语与工具（攻关任务一）")
para("赛题要求定义出 AI 友好的元数据，并说明元数据的组织形式是工具设计，让大模型通过工具获取有效上下文。我们的做法是把元数据拆成四类登记项，每一类都有明确的字段与消费方：表定义给模型看有哪些表，指标注册表给模型看指标怎么算，业务术语表把口语翻译成字段条件，工具目录说明这些元数据可以怎么取。四类登记项以 TypeScript 常量形式内置在服务端，与数据库表结构同源，避免了「文档写一套、代码做一套」。")
para("表定义覆盖赛题给出的九张表，每张表记录表名、中文名、业务用途，每个字段记录字段名、类型、中文名与业务口径。建表语句由表定义直接生成，安全围栏的列名白名单也从同一份定义派生，因此「文档、建表语句、校验白名单」三处必然一致，不会出现改了建表忘了改白名单的情况。")
para("指标注册表登记 25 个客户营销常用指标，包括客户数、总资产、日均资产、人均资产、持仓市值、持仓笔数、持仓成本、近 90 日与近 180 日交易笔数与金额、净流入、平均持仓收益率、活跃客户数等。每个指标记录唯一英文名、中文名、口径说明、单位、依赖表与参考 SQL 片段。参考片段只是给模型的提示，模型写出的查询仍须通过安全围栏校验；指标口径说明则直接决定了「近 90 日」这类时间窗在哪张表上生效。")
para("业务术语表登记 11 条口语说法及其口径映射，例如高净值客户（总资产不低于 1000 万元）、活跃客户（近 90 日内有交易）、沉默客户（近 90 日内既无交易也无资金流入）、净流入（流入金额减流出金额）、主协办关系（主办承担主要服务责任）。术语定义与合成数据的生成口径保持同源：客群标签字段只按总资产划分，活跃与沉默由交易与资金流水派生，并由单元测试断言两者一致，避免出现「照元数据写 SQL，反而与报表对不上」。")
para("组织形式上，我们没有把上述元数据整体拼进提示词，而是暴露成 5 个可调用工具，由模型按需取用。这样做有三个好处：上下文预算可控，不必为一次简单计数载入九张表的全部字段；模型先看表清单、再看字段、最后取口径，取用过程本身留在审计里，可以复盘它是根据什么信息写出这条查询的；元数据更新后只需改登记表，工具返回值随之变化，不需要动提示词。")
