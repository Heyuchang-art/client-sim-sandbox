h2("3.7 群体行为模拟的数学模型")

para("本节给出引擎的完整计算过程。前几节说明的是模块之间怎么连接，真正决定数值结果的是这里的计算。整体顺序是：读取场景参数 → 筛选目标客户 → 生成初始状态 → 建立关系网络 → 按时间步循环更新 → 换算行为倾向并汇总成群体指标与干预队列。以下记客户 i 在第 t 个时间步的恐慌为 p_i(t)，场景跌幅的绝对值为 s，涉及的六项心理参数分别为损失厌恶 λ、从众敏感度 h、收益追求 a、投资纪律 d、长期耐心 k 与机构信任 trust，取值均在 0 到 1 之间。")

para("第一步是把市场跌幅落到每个客户身上。系统不让所有客户承受同一个跌幅，而是先由心理特征与所持产品算出各自的持仓弹性，再据此得到回撤。")

formula("① 持仓弹性与个体回撤", [
    "β_i = clamp( 0.62 + 0.42·aᵢ + 0.24·hᵢ − 0.16·dᵢ + 0.55·(vᵢ − 1) + ηᵢ , 0.35 , 1.9 )",
    "DDᵢ = clamp( s × 100 × βᵢ + ξᵢ , 0.4 , 45 )",
], note="vᵢ 为该客户所持产品的波动系数，ηᵢ、ξᵢ 是按随机种子生成的个体扰动。含义是：市场跌 1%，这位客户实际承受多少，由他自己的收益追求、从众倾向、纪律水平决定，再叠加产品本身的波动。同一个客户在不同行情下跌幅成比例；同一场行情下不同客户跌幅不同。")

para("第二步是初始状态。客户在行情开始前已有一定恐慌，并在此后按时间步演化。")

formula("② 初始恐慌与冲击落地", [
    "pᵢ(0) = clamp( 0.1 + 0.35·λᵢ + 0.12·hᵢ + DDᵢ/100 − 0.18·dᵢ )",
    "pᵢ ← clamp( 0.42·pᵢ(0) + s·(0.72 + 0.78·λᵢ) − 0.05·dᵢ )",
], note="第二行表示行情冲击真正打进来的那一步：原有恐慌只留 42%，主体来自按损失厌恶加权的市场冲击。")

para("第三步进入时间步循环。每一步先计算当步的行情压力，再计算邻居传导，最后合成新的恐慌。")

formula("③ 当步行情压力", [
    "S(t) = ( 0.095 + 0.82·s ) × shape( H , t/(T−1) )",
    "shape = clamp( ln(max(H,1)/24) / ln 24 , −1 , 1 ) 的线性函数",
], note="H 为持续时间（小时），T 为总段数。持续时间越长，shape 越大，压力衰减越慢。需要如实说明：在该函数的取值范围内压力随步长单调递减，因此恐慌峰值恒定出现在第一段，时长的影响体现在峰值高度与衰减速度，而不是峰值位置。")

formula("④ 邻居情绪传导", [
    "Cᵢ(t) = [ Σⱼ wᵢⱼ·pⱼ(t−1) / Σⱼ wᵢⱼ ] × hᵢ × ( 0.16 + 0.55·s )",
], note="wᵢⱼ 是客户 i 与 j 之间的三类关系权重：相似性 0.72、社交影响 1.0、统一服务触达 0.42 至 0.58。括号内一项表示行情跌得越深，情绪传导越快。这一项是「从众效应」在模型中的具体形式，也是本项目区别于单客户画像工具的关键所在。")

formula("⑤ 逐时间步恐慌更新", [
    "pᵢ(t) = clamp( 0.56·pᵢ(t−1) + S(t)·λᵢ + Cᵢ(t) + Aᵢ(t) + Wᵢ(t) − Bᵢ(t) − 0.09·dᵢ − 0.045·kᵢ + εᵢ )",
], note="七项含义：0.56 是上一段恐慌的留存比例（对应记忆层）；S(t)·λᵢ 是按损失厌恶加权的市场压力；Cᵢ(t) 是邻居传导；Aᵢ(t) 是广播式沟通引起的额外警觉；Wᵢ(t) 是主动触达本身惊动平静客户的唤醒效应；Bᵢ(t) 是主动沟通的安抚；投资纪律与长期耐心起自我抑制作用；εᵢ 是幅度 ±0.0175 的随机扰动。")

para("第四步把恐慌换算成可执行的行为倾向。四项倾向都用 logistic 函数把线性组合压缩到 0 到 1 之间。")

formula("⑥ 行为倾向换算", [
    "sellᵢ    = clamp( σ( (pᵢ − 0.58)·5.2 + 0.7·hᵢ − 1.1·dᵢ ) )",
    "buyᵢ     = clamp( σ( (0.34 − pᵢ)·4.4 + 1.2·aᵢ + 0.35·trustᵢ ) × 0.58 )",
    "holdᵢ    = clamp( 1 − buyᵢ − sellᵢ )",
    "consultᵢ = clamp( σ( (pᵢ − 0.32)·3.4 + 0.65·trustᵢ − 0.25·dᵢ ) × 0.72 )",
    "complaintᵢ = clamp( σ( (pᵢ − 0.62)·4.2 − 2.3·trustᵢ + 7·tone ) × 0.42 )",
    "churnᵢ     = clamp( σ( (0.45 − trustᵢ)·5 + 2.2·complaintᵢ ) × 0.38 )",
], note="σ 为 logistic 函数。买入、持有、卖出三项恒之和为 1，因此三者可以直接比较。tone 为该策略话术的刺激强度，若草稿被合规拦截则置零。投诉与流失由恐慌和信任共同决定，不单独受话术影响。")

para("最后是汇总。每个时间步结束后对所有客户取均值，得到该步的群体恐慌、卖出、投诉、流失、信任、触达覆盖与传播强度；同时逐客户记录整个模拟期内的峰值暴露（peakRisk 及其所在段），用于生成干预队列，而不是用期末状态排序——因为干预生效后期末状态会普遍回落，按期末值排序会得到一份人人低风险的名单。")

