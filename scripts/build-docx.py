def _shade(cell, fill):
    tcPr = cell._tc.get_or_add_tcPr()
    shd = OxmlElement("w:shd")
    shd.set(qn("w:val"), "clear")
    shd.set(qn("w:color"), "auto")
    shd.set(qn("w:fill"), fill)
    tcPr.append(shd)


def formula(title, lines, note=None):
    """公式/伪代码块：浅底纹单格表 + 等宽字体，与正文视觉区分。"""
    if title:
        tp = doc.add_paragraph()
        tp.paragraph_format.space_before = Pt(8)
        tp.paragraph_format.space_after = Pt(3)
        style_run(tp.add_run(title), size=11, bold=True, ea="微软雅黑", ascii_font="微软雅黑", color=RGBColor(0x1E, 0x3A, 0x8A))
    t = doc.add_table(rows=1, cols=1)
    t.alignment = WD_TABLE_ALIGNMENT.CENTER
    cell = t.cell(0, 0)
    _shade(cell, "F3F6FB")
    for i, line in enumerate(lines):
        cp = cell.paragraphs[0] if i == 0 else cell.add_paragraph()
        cp.paragraph_format.space_after = Pt(2)
        cp.paragraph_format.line_spacing = 1.35
        style_run(cp.add_run(line), size=10.5, ea="宋体", ascii_font="Consolas", color=RGBColor(0x11, 0x18, 0x27))
    if note:
        np2 = doc.add_paragraph()
        np2.paragraph_format.space_before = Pt(3)
        np2.paragraph_format.space_after = Pt(10)
        style_run(np2.add_run(note), size=10, ea="宋体", color=RGBColor(0x55, 0x5F, 0x70))
    else:
        sp = doc.add_paragraph()
        sp.paragraph_format.space_after = Pt(8)
    return t


def figure(rel_path, caption, width_cm=15.4, max_height_cm=19.0):
    path = os.path.join(ROOT, rel_path)
    from PIL import Image
    with Image.open(path) as probe:
        ratio = probe.height / probe.width
    fitted = min(width_cm, max_height_cm / ratio)
    p = doc.add_paragraph()
    p.alignment = WD_ALIGN_PARAGRAPH.CENTER
    p.paragraph_format.space_before = Pt(8)
    p.paragraph_format.space_after = Pt(2)
    p.add_run().add_picture(path, width=Cm(fitted))
    c = doc.add_paragraph()
    c.alignment = WD_ALIGN_PARAGRAPH.CENTER
    c.paragraph_format.space_after = Pt(12)
    style_run(c.add_run(caption), size=10.5, ea="微软雅黑", ascii_font="微软雅黑", color=RGBColor(0x47, 0x55, 0x69))
    return p


def table(headers, rows, widths=None, caption=None):
    t = doc.add_table(rows=1, cols=len(headers))
    t.style = "Table Grid"
    t.alignment = WD_TABLE_ALIGNMENT.CENTER
    for i, head in enumerate(headers):
        cell = t.rows[0].cells[i]
        cell.text = ""
        par = cell.paragraphs[0]
        par.alignment = WD_ALIGN_PARAGRAPH.CENTER
        style_run(par.add_run(head), size=10.5, bold=True, ea="微软雅黑", ascii_font="微软雅黑")
    for row in rows:
        cells = t.add_row().cells
        for i, value in enumerate(row):
            cells[i].text = ""
            par = cells[i].paragraphs[0]
            par.alignment = WD_ALIGN_PARAGRAPH.CENTER if i > 0 else WD_ALIGN_PARAGRAPH.LEFT
            style_run(par.add_run(str(value)), size=10.5)
    if widths:
        for row in t.rows:
            for i, w in enumerate(widths):
                row.cells[i].width = Cm(w)
    if caption:
        c = doc.add_paragraph()
        c.alignment = WD_ALIGN_PARAGRAPH.CENTER
        c.paragraph_format.space_before = Pt(4)
        c.paragraph_format.space_after = Pt(12)
        style_run(c.add_run(caption), size=10.5, ea="微软雅黑", ascii_font="微软雅黑", color=RGBColor(0x47, 0x55, 0x69))
    return t

