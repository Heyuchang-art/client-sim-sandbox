h2("3.2 Agent Loop 与 Harness 分工")
para("Harness 由六个部件组成。Planner 把自然语言目标翻译成结构化步骤与工具序列；Executor 逐步执行并把每一步的输入输出落库；Tool Registry 注册八个工具，覆盖场景抽取、客户查询、画像构建、关系网络构建、策略起草、模拟执行、合规审查与报告生成；Memory 保存结构化画像与会话记忆摘要；Reflector 在任务成功后评估结果并沉淀候选技能；Policy Gateway 是模型的硬边界，其草稿级拦截前置于数值模拟，不参与智能体的自由决策。")
