para("为验证这套建模确实让结论随场景变化，我们做了 630 个场景的验收扫描（跌幅 7 档、时长 5 档、步数 3 档、随机种子 3 个、客群口径 2 种）。需要如实区分两类结论。第一类是与效用权重无关的结构性质，这是我们的主要验收对象：跌幅越大、推荐方案的人工深度不下降（90 条场景序列零违反）；微跌（5%）不推荐高人工深度方案；重挫（50%）不推荐放弃触达的方案；同种子完全复现；每次推荐都带三项归因分解。这些性质在设计上要求跨权重成立，因此可以失败、有信息量；实测它们在默认与中等效用权重下全部成立，在极端打扰权重下存在一处已定位的边界，见下文。第二类是与效用权重相关的夺冠配比：三种锚点各自夺冠 48.9%、26.3%、24.8%，但这是业务效用权重的函数而不是引擎的固有性质——把唤醒权重从 2 调到 0，不主动沟通的夺冠占比会从 48.9% 降到 1.3%。因此本申报书只把配比连同权重敏感性曲面一起引用，不作为「结论不写死」的证据。已知边界：把打扰权重取到极端值（8）且时长压到 6 小时时，40% 到 50% 的区间会出现一次深度回落，推荐由分群沟通回到统一风险提示。实测机制是：唤醒罚分本身随恐慌上升而衰减（wake = 唤醒系数 × (1 − 上一步恐慌) × 本步新增触达），而 λ_wake 把它放大了 8 倍；广播式的唤醒基数更大，因此衰减带来的减负也更多（实测 50% 档广播式的唤醒罚分比 40% 档低约 42%），而人工成本不随恐慌衰减，于是推荐在高冲击档翻回低成本的广播式。需要特别指出：恐慌并未饱和（该场景峰值约 58%–84%（扫描脚本同组参数下 40% 档为 57.5%/62.5%/68.4%，50% 档为 70.4%/76.5%/83.8%），明显低于上限 1.0），因此这**不是**饱和效应。该配置不属于默认口径，已记录为模型迭代项；唤醒项是否应改为不随恐慌衰减，属于待评估的建模选择。此外重构前三套策略在 840 个场景中由分群沟通 100% 夺冠，排序由常数写死，本轮是针对这一缺陷的重做。")

